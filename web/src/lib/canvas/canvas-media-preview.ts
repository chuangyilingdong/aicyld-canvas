import { buildLibTVVideoPreviewUrl } from "@/lib/canvas/libtv-import";
import { CanvasNodeType, type CanvasNodeData } from "@/types/canvas";
import { parseVideoBoolean } from "@/lib/video-generation-options";
import { isSilentDirectorClayVideo } from "@/lib/canvas/director/director-clay-output";

export function inferVideoHasAudio(metadata: CanvasNodeData["metadata"]): boolean | undefined {
    if (isSilentDirectorClayVideo(metadata)) return false;
    if (typeof metadata?.hasAudio === "boolean") return metadata.hasAudio;
    return parseVideoBoolean(metadata?.generateAudio);
}

/**
 * Returns an image source that is safe to mount for a passive video preview.
 * The original video URL is deliberately never returned: callers must fall
 * back to a video icon instead of creating a decoder outside the active node.
 */
export function canvasNodeVideoPreviewUrl(node: CanvasNodeData) {
    if (node.type !== CanvasNodeType.Video) return "";
    const content = node.metadata?.content || "";
    const generatedPreview = node.metadata?.videoPreview?.content || "";
    if (generatedPreview && generatedPreview !== content) return generatedPreview;
    const explicitPreview = node.metadata?.previewContent || "";
    if (explicitPreview && explicitPreview !== content) return explicitPreview;
    return ownedResourceVideoPosterUrl(node.metadata?.storageKey, content) || buildLibTVVideoPreviewUrl(content);
}

export function canvasVideoAssetPreviewUrl(videoUrl: string, coverUrl?: string) {
    const explicitCover = coverUrl?.trim() || "";
    if (explicitCover && explicitCover !== videoUrl) return explicitCover;
    return ownedResourceVideoPosterUrl("", videoUrl) || buildLibTVVideoPreviewUrl(videoUrl);
}

export const CANVAS_SERVER_VIDEO_POSTER_WIDTH = 480;

/**
 * Hosted videos already have an owned resource identity. Their cover can be
 * generated by the backend instead of downloading a video decoder merely to
 * render a static card.
 */
export function ownedResourceVideoPosterUrl(storageKey?: string, content?: string) {
    const resourceId = ownedResourceId(storageKey, content);
    if (!resourceId) return "";
    const path = `/api/resources/${encodeURIComponent(resourceId)}/file`;
    return `${path}?proxy=1&thumbnail=${CANVAS_SERVER_VIDEO_POSTER_WIDTH}`;
}

function ownedResourceId(storageKey?: string, content?: string) {
    const fromKey = storageKey?.startsWith("resource:") ? storageKey.slice("resource:".length).trim() : "";
    if (fromKey) return fromKey;
    const path = content?.split(/[?#]/, 1)[0] || "";
    const match = path.match(/\/(?:api\/)?resources\/([^/]+)\/file$/);
    if (!match) return "";
    try {
        return decodeURIComponent(match[1]);
    } catch {
        return "";
    }
}
